//! Comments must come back where they were. A comment above an element travels with that element
//! (into its shard, through reordering); one after an element's last child stays before its
//! closing tag; one in an element's text is part of its mixed content. Before, all of an element's
//! comments were merged into one string written after its children -- moved, and at the root
//! written back as JSON text -- and such files were later skipped instead.

