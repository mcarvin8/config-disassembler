async fn roundtrip(
    base: &Path,
    stem: &str,
    ext: &str,
    content: &str,
    format: &str,
    grouped: bool,
) -> String {
    let source = base.join(format!("{stem}.{ext}"));
    std::fs::write(&source, content).unwrap();
    DisassembleXmlFileHandler::new()
        .disassemble(
            source.to_str().unwrap(),
            Some("fullName,name"),
            Some(if grouped {
                "grouped-by-tag"
            } else {
                "unique-id"
            }),
            false,
            true,
            ".xmldisassemblerignore",
            format,
            None,
            None,
            None,
            None,
        )
        .await
        .expect("disassemble");
    assert!(
        !source.exists(),
        "post-purge should remove the original: {stem}"
    );
    ReassembleXmlFileHandler::new()
        .reassemble(base.join(stem).to_str().unwrap(), Some(ext), true, None)
        .await
        .expect("reassemble");
    std::fs::read_to_string(&source).unwrap()
}

#[tokio::test]
async fn comments_come_back_in_place_in_every_format_and_strategy() {
    for (stem, ext, content) in CASES {
        for format in ["xml", "json", "json5", "yaml"] {
            for grouped in [false, true] {
                let tmp = tempfile::tempdir().unwrap();
                let rebuilt = roundtrip(tmp.path(), stem, ext, content, format, grouped).await;
                assert_eq!(rebuilt, *content, "{stem} / {format} / grouped {grouped}");
            }
        }
    }
}

#[tokio::test]
async fn comment_outside_the_root_leaves_the_file_in_place() {
    // Before or after the root element there is no element for it to travel with.
    let content = r#"<?xml version="1.0" encoding="UTF-8"?>
<!-- generated by a tool -->
<FlexiPage xmlns="http://soap.sforce.com/2006/04/metadata">
    <flexiPageRegions>
        <name>region1</name>
        <type>Region</type>
    </flexiPageRegions>
</FlexiPage>
"#;
    let tmp = tempfile::tempdir().unwrap();
    let source = tmp.path().join("Generated.flexipage-meta.xml");
    std::fs::write(&source, content).unwrap();
    DisassembleXmlFileHandler::new()
        .disassemble(
            source.to_str().unwrap(),
            None,
            Some("unique-id"),
            false,
            true,
            ".xmldisassemblerignore",
            "xml",
            None,
            None,
            None,
            None,
        )
        .await
        .expect("disassemble");
    assert_eq!(std::fs::read_to_string(&source).unwrap(), content);
    assert!(!tmp.path().join("Generated").exists());
}

#[tokio::test]
async fn mixed_content_with_a_comment_is_stable_across_round_trips() {
    // Found by config-disassembler-node's round-trip fuzz test: a comment followed by CDATA and
    // text after a child element. Each round trip must give the same bytes as the one before.
    let content = r#"<?xml version="1.0" encoding="UTF-8"?>
<FuzzRoot xmlns="http://soap.sforce.com/2006/04/metadata"><item><fullName>Item0</fullName><!-- --><![CDATA[]]>(</item><item><fullName>Item1</fullName></item></FuzzRoot>"#;
    let tmp = tempfile::tempdir().unwrap();
    let mut previous: Option<String> = None;
    for pass in 1..=3 {
        let rebuilt = roundtrip(
            tmp.path(),
            "Fuzz",
            "fuzz-meta.xml",
            content_or(&previous, content),
            "xml",
            false,
        )
        .await;
        assert!(
            rebuilt.contains("<!-- -->") && rebuilt.contains('('),
            "pass {pass}: {rebuilt}"
        );
        if let Some(prev) = &previous {
            assert_eq!(&rebuilt, prev, "pass {pass} changed the output");
        }
        previous = Some(rebuilt);
    }
}

fn content_or<'a>(previous: &'a Option<String>, original: &'a str) -> &'a str {
    previous.as_deref().unwrap_or(original)
}
